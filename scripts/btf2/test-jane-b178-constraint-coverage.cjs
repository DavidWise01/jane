'use strict';
const assert=require('node:assert/strict');
const {TEMPLATE}=require('./jane-b161-formic-agent.cjs');
const {parseTemplate}=require('./jane-b177-semantic-template.cjs');
const {fixtures,expectedIds,run,audit}=require('./jane-b178-constraint-coverage.cjs');
const original=fixtures(),ids=expectedIds();
assert.equal(ids.length,48);
assert.equal(new Set(ids).size,48);
assert.equal(original.filter(x=>x.group==='fields').length,15);
assert.equal(original.filter(x=>x.group==='headings').length,12);
assert.equal(original.filter(x=>x.group==='grammar').length,4);
assert.equal(original.filter(x=>x.group==='body').length,12);
assert.equal(original.filter(x=>x.group==='encoding').length,5);
assert.deepEqual(parseTemplate(TEMPLATE).fields,{name:'Bug report',about:'Report a reproducible defect',
 title:'""',labels:'bug',assignees:'""'});
const good=run();assert.equal(good.status,'CONSTRAINT_COVERAGE_PASS_NO_EXECUTION');
assert.equal(good.observed,48);assert.equal(good.errors.length,0);
assert.equal(audit(good).status,'PASS');
assert.equal(good.authority.mayCreatePR,false);assert.equal(good.governance.repoCodeExecuted,false);
const deleted=run({cases:original.slice(1)});
assert.equal(deleted.status,'HOLD');
assert(deleted.errors.some(x=>x.startsWith('MISSING_FIXTURE:')));
const duplicated=run({cases:[...original,original[0]]});
assert.equal(duplicated.status,'HOLD');
assert(duplicated.errors.some(x=>x.includes('DUPLICATE')));
const untested=run({cases:original.map((x,i)=>i===0?{...x,make:()=>TEMPLATE}:x)});
assert.equal(untested.status,'HOLD');
assert(untested.errors.some(x=>x.startsWith('FIXTURE_FAILED:')));
const changedExpectation=run({cases:original.map((x,i)=>i===0?{...x,error:'UNEXPECTED_ACCEPTANCE'}:x)});
assert.equal(changedExpectation.status,'HOLD');
assert(changedExpectation.errors.some(x=>x.startsWith('FIXTURE_CONTRACT_CHANGED:')));
const unsafeParser=run({parser:()=>({fields:{labels:'bug'},headings:['a','b','c','d','e','f']})});
assert.equal(unsafeParser.status,'HOLD');
assert(unsafeParser.errors.some(x=>x.includes('UNEXPECTED_ACCEPTANCE')));
const baselineRejected=run({parser:()=>{throw Error('reject all')}});
assert.equal(baselineRejected.status,'HOLD');
const tampered={...good,authority:{...good.authority,mayMerge:true}};
assert.equal(audit(tampered).status,'HOLD');
const modifiedRow={...good,observations:[...good.observations]};
modifiedRow.observations[0]={...modifiedRow.observations[0],mutationRejectedAsExpected:false};
assert.equal(audit(modifiedRow).status,'HOLD');
console.log('PASS B178: 48 controls, missing/duplicate/weakened fixtures HOLD, false-pass parser HOLD, altered authority HOLD');
