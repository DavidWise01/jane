'use strict';
const assert=require('node:assert/strict');
const m=require('./jane-b161-formic-agent.cjs');
const repo={full_name:'DavidWise01/sample',private:false,archived:false,disabled:false,fork:false,default_branch:'main'};
const policy={schema:'FORMIC-REPO-POLICY-v1',enabled:true,allowed_repairs:['BUG_REPORT_TEMPLATE'],max_open_pull_requests:1};
assert.equal(m.repoGate(repo),'ELIGIBLE');
assert.equal(m.policyGate(policy),'ELIGIBLE');
assert.equal(m.decide(repo,policy).decision,'PROPOSE_DRAFT_PR');
assert.equal(m.decide(repo,{...policy,enabled:false}).decision,'HOLD_NOT_OPTED_IN');
assert.equal(m.decide(repo,null).decision,'HOLD_MISSING_POLICY');
assert.equal(m.decide(repo,{...policy,allowed_repairs:[]}).decision,'HOLD_REPAIR_NOT_ALLOWED');
assert.equal(m.decide({...repo,private:true},policy).decision,'HOLD_PRIVATE');
assert.equal(m.decide({...repo,archived:true},policy).decision,'HOLD_ARCHIVED_DISABLED_OR_FORK');
assert.equal(m.decide({...repo,full_name:'SomeoneElse/sample'},policy).decision,'HOLD_OUT_OF_SCOPE');
assert.equal(m.decide(repo,policy,{fileExists:true}).decision,'NO_CHANGE_FILE_EXISTS');
assert.equal(m.decide(repo,policy,{prExists:true}).decision,'NO_CHANGE_PR_EXISTS');
assert.equal(m.decide(repo,policy,{branchExists:true}).decision,'HOLD_BRANCH_EXISTS');
assert.match(m.TEMPLATE,/Steps to reproduce/);
assert.match(m.TEMPLATE,/Remove secrets/);
console.log('PASS B161: owner scope, explicit opt-in, safe template, skip-existing, PR-only plan, archive/private holds');
