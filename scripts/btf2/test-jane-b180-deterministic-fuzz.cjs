'use strict';
const assert=require('node:assert/strict');
const {TEMPLATE}=require('./jane-b161-formic-agent.cjs');
const {parseIndependent}=require('./jane-b179-independent-parser.cjs');
const {SCHEMA,SEED,ROUNDS,operations,reproducibleMutations,run,audit}=require('./jane-b180-deterministic-fuzz.cjs');
const first=reproducibleMutations(),second=reproducibleMutations();
assert.equal(operations().length,20);
assert.equal(first.length,400);
assert.deepEqual(first,second);
assert.equal(new Set(first.map(x=>x.id)).size,400);
const valid=run();
assert.equal(valid.status,'DETERMINISTIC_FUZZ_AGREEMENT_NO_EXECUTION');
assert.equal(valid.schema,SCHEMA);
assert.equal(valid.counts.expected,400);
assert.equal(valid.counts.agreed,400);
assert.equal(valid.counterexamples.length,0);
assert.equal(audit(valid).status,'PASS');
assert.equal(valid.authority.mayCreatePR,false);
assert.equal(valid.governance.repositoryCodeExecuted,false);
const alternative=run({seed:SEED+1});
assert.equal(alternative.status,'DETERMINISTIC_FUZZ_AGREEMENT_NO_EXECUTION');
assert.notEqual(alternative.inputDigest,valid.inputDigest);
const overaccept=run({second:()=>parseIndependent(TEMPLATE)});
assert.equal(overaccept.status,'HOLD');
assert(overaccept.counterexamples.length>0);
assert.equal(overaccept.counterexamples[0].independent.accepted,true);
const overreject=run({second:()=>{throw Error('EVERYTHING_BLOCKED')}});
assert.equal(overreject.status,'HOLD');
assert(overreject.issues.includes('CANONICAL_DISAGREEMENT'));
const missing=run({mutations:first.slice(1)});
assert.equal(missing.status,'HOLD');
assert(missing.issues.some(x=>x.startsWith('MISSING_CASE:')));
const changed=run({mutations:first.map((x,i)=>i===0?{...x,value:x.value+'extra'}:x)});
assert.equal(changed.status,'HOLD');
assert(changed.issues.some(x=>x.startsWith('MUTATION_CONTRACT_MISMATCH:')));
const duplicate=run({mutations:[first[0],...first.slice(0,-1)]});
assert.equal(duplicate.status,'HOLD');
assert(duplicate.issues.some(x=>x==='INVALID_OR_DUPLICATE_CASE'));
const changedAuthority={...valid,authority:{...valid.authority,mayMerge:true}};
assert.equal(audit(changedAuthority).status,'HOLD');
const changedDigest={...valid,counts:{...valid.counts,agreed:399}};
assert.equal(audit(changedDigest).status,'HOLD');
assert.throws(()=>reproducibleMutations({rounds:65}),/INVALID_FUZZ_PARAMETERS/);
console.log('PASS B180: 400 seeded two-parser comparisons, seed repeat, permissive and rejecting parsers HOLD, missing/mutated/duplicate contract HOLD');
