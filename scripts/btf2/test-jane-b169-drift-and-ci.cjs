'use strict';
const assert=require('node:assert/strict');
const {build}=require('./jane-b168-proof-proposal.cjs');
const {classify,inspect,report}=require('./jane-b169-drift-and-ci.cjs');
const repo={full_name:'DavidWise01/jane',default_branch:'main',private:false,visibility:'public',archived:false,disabled:false,fork:false};
const policy={schema:'FORMIC-REPO-POLICY-v1',enabled:true,allowed_repairs:['BUG_REPORT_TEMPLATE'],max_open_pull_requests:1};
const b167={repository:repo.full_name,status:'POLICY_EVIDENCE_PRESENT',mayCreatePR:false,mayRetry:false,mayMerge:false};
const sha='a'.repeat(40),proposal=build({repo,policy,b167,baseSha:sha});
assert.equal(proposal.status,'PROPOSAL_ONLY');
const green=[{name:'tests',status:'completed',conclusion:'success',app:{id:1},started_at:'2026-11-05T00:00:00Z'}];
const known={refSha:sha,fileState:'ABSENT',checks:green,statuses:[{context:'ci',state:'success'}],checkRunsComplete:true,statusesComplete:true};
const good=classify(proposal,known);
assert.equal(good.status,'BASE_OBSERVED_PASS_NOT_PROPOSAL_VALIDATED');
assert.equal(good.proposalChecksExecuted,false);assert.equal(good.mayCreatePR,false);
assert.equal(classify(proposal,{...known,refSha:'b'.repeat(40)}).status,'HOLD');
assert.equal(classify(proposal,{...known,fileState:'PRESENT'}).status,'HOLD');
assert.equal(classify(proposal,{...known,checks:[]}).status,'BASE_OBSERVED_PASS_NOT_PROPOSAL_VALIDATED');
assert.equal(classify(proposal,{...known,checks:[],statuses:[]}).status,'HOLD');
assert.equal(classify(proposal,{...known,checks:[{...green[0],conclusion:'failure'}]}).status,'HOLD');
assert.equal(classify(proposal,{...known,checks:[{...green[0],status:'in_progress'}]}).status,'HOLD');
assert.equal(classify(proposal,{...known,statusesComplete:false}).status,'HOLD');
const corrupt=JSON.parse(JSON.stringify(proposal));corrupt.envelope.proposal.changes[0].after+='damage';
assert.equal(classify(corrupt,known).status,'HOLD');
const ref='/repos/DavidWise01/jane/git/ref/heads/main';
const mock=async url=>{
 if(url==='/repos/DavidWise01/jane')return{full_name:repo.full_name,owner:{login:'DavidWise01'},private:false,archived:false,disabled:false,fork:false,default_branch:'main'};
 if(url===ref)return{object:{sha}};
 if(url.includes('/contents/'))return null;
 if(url.endsWith('/check-runs?per_page=100'))return{total_count:1,check_runs:green};
 if(url.endsWith('/status'))return{total_count:1,statuses:[{context:'ci',state:'success'}]};
 throw Error('UNEXPECTED_ROUTE '+url);
};
(async()=>{
 const one=await inspect(proposal,'',mock);assert.equal(one.status,'BASE_OBSERVED_PASS_NOT_PROPOSAL_VALIDATED');
 let reads=0;
 const drift=await inspect(proposal,'',async url=>url===ref?{object:{sha:++reads===1?sha:'c'.repeat(40)}}:mock(url));
 assert.equal(drift.status,'HOLD');
 const changedBranch=await inspect(proposal,'',async url=>url==='/repos/DavidWise01/jane'?{...(await mock(url)),default_branch:'master'}:mock(url));
 assert.equal(changedBranch.status,'HOLD');
 const inaccessible=await inspect(proposal,'',async url=>url.includes('/check-runs')?Promise.reject(Error('403')):mock(url));
 assert.equal(inaccessible.status,'HOLD');
 const record=report([one,drift]);assert.equal(record.counts.baseObservedPass,1);assert.equal(record.governance.automaticWrites,false);
 console.log('PASS B169: base SHA drift, file presence, CI failure/missing evidence, TOCTOU read, no write or proposal checks');
})().catch(e=>{console.error(e);process.exitCode=1});
