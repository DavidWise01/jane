'use strict';
const assert=require('node:assert/strict');
const {historyFor,plan,Decisions}=require('./jane-b151-scout-exploration.cjs');
const obs=(w,s,status='SIMULATED_CROSSING')=>({witness:w,slot:s,status,physicalPromotion:false,source:'B150_PIXEL_SCOUT',frame:'B150_VISUAL_UNITS'});
let empty=plan([],{witness:'a1',radius:21});assert.equal(empty.targetSlot,'S1');
const own=[obs('a1','S1'),obs('b1','S2'),obs('a1','S2','HOLD')];
const h=historyFor(own,'a1');assert.equal(h[0].visits,1);assert.equal(h[1].holds,1);
const a=plan(own,{witness:'a1',radius:25});assert.equal(a.targetSlot,'S2');
const b=plan(own,{witness:'b1',radius:25});assert.equal(b.targetSlot,'S1');
assert.equal(a.physicalPromotion,false);assert.equal(a.basis,'OWN_WITNESS_OBSERVATIONS_ONLY');
assert.deepEqual(plan(own,{witness:'a1',radius:25}),a);
const v=plan([obs('a1','S1'),obs('a1','S2'),obs('a1','S3'),obs('a1','S4'),obs('a1','S5'),obs('a1','S3','HOLD')],{witness:'a1',radius:40});
assert.equal(v.targetSlot,'S3');assert.equal(v.reason,'REVISIT_UNCERTAIN');
assert.throws(()=>plan([],{witness:'quorum',radius:3}),/INVALID/);
assert.throws(()=>plan([],{witness:'a1',radius:NaN}),/INVALID/);
assert.equal(historyFor([obs('a1','S1','VERIFIED_PHYSICS')],'a1')[0].visits,0);
const j=new Decisions();j.append(a);j.append(b);assert.deepEqual(j.replay(),{status:'PASS',count:2,quorum:false,physicalPromotions:0});
j.entries[0].choice.targetSlot='S5';assert.throws(()=>j.replay(),/CHAIN/);
console.log('PASS B151: independent scout state, deterministic slot selection, HOLD revisit, cross-witness isolation, SHA256 decision log tamper detection');
