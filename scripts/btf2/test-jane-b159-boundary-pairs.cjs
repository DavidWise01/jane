'use strict';
const assert=require('node:assert/strict');
const {gate,BoundaryBook}=require('./jane-b159-boundary-pairs.cjs');
assert.equal(gate(122,123,'+').status,'BOUNDARY_OPEN_FOR_OBSERVATION');
assert.equal(gate(244,245,'+').arrival,'c1');
assert.equal(gate(366,1,'+').arrival,'a1');
assert.equal(gate(123,122,'-').arrival,'a1');
assert.equal(gate(62,63,'+').status,'HOLD');
const l=new BoundaryBook();
l.open({boundaryId:'AB',from:122,to:123,sign:'+'});
l.open({boundaryId:'BC',from:244,to:245,sign:'+'});
l.open({boundaryId:'CA',from:366,to:1,sign:'+'});
assert.equal(l.view('AB').status,'UNMATCHED_HOLD');
l.append({id:'ab-dep',boundaryId:'AB',side:'DEPARTURE',witness:'a1',sawCrossing:true,note:'left the edge',physicalPromotion:false});
assert.equal(l.view('AB').status,'UNMATCHED_HOLD');
l.append({id:'ab-arr',boundaryId:'AB',side:'ARRIVAL',witness:'b1',sawCrossing:false,note:'did not observe arrival',physicalPromotion:false});
assert.equal(l.view('AB').status,'DISAGREEMENT_PRESERVED');
assert.equal(l.view('AB').reports.length,2);
l.append({id:'bc-dep',boundaryId:'BC',side:'DEPARTURE',witness:'b1',sawCrossing:true,note:'departure seen',physicalPromotion:false});
l.append({id:'bc-arr',boundaryId:'BC',side:'ARRIVAL',witness:'c1',sawCrossing:true,note:'arrival seen',physicalPromotion:false});
assert.equal(l.view('BC').status,'TWO_SIDES_RECORDED');
assert.equal(l.view('CA').status,'UNMATCHED_HOLD');
assert.equal(l.audit().status,'PASS');
assert.equal(l.audit().disagreements,1);
assert.equal(l.audit().unmatched,1);
assert.throws(()=>l.append({id:'foreign',boundaryId:'AB',side:'ARRIVAL',witness:'a1',sawCrossing:true,note:'',physicalPromotion:false}),/FOREIGN/);
assert.throws(()=>l.append({id:'ab-dep',boundaryId:'AB',side:'DEPARTURE',witness:'a1',sawCrossing:true,note:'',physicalPromotion:false}),/DUPLICATE/);
assert.throws(()=>l.append({id:'invalid',boundaryId:'AB',side:'DEPARTURE',witness:'a1',sawCrossing:true,note:'',physicalPromotion:true}),/PROMOTION/);
assert.throws(()=>l.open({boundaryId:'INVALID',from:62,to:63,sign:'+'}),/NOT_A_CROSS/);
const tampered=l.logs.a1[0].record;tampered.sawCrossing=false;assert.equal(l.audit().status,'HOLD');
console.log('PASS B159: paired independent reports, disagreement preservation, unmatched HOLD, source ownership, append-only SHA256 audit, no quorum');
