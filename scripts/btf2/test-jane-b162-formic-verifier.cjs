'use strict';
const assert=require('node:assert/strict');
const {checkSummary,disposition,classifyLedger,run}=require('./jane-b162-formic-verifier.cjs');
const ok={name:'build',status:'completed',conclusion:'success',app:{id:1},started_at:'2026-11-01T00:00:00Z'};
const bad={name:'lint',status:'completed',conclusion:'failure',app:{id:1},started_at:'2026-11-01T00:00:00Z'};
const pending={name:'test',status:'in_progress',conclusion:null,app:{id:1}};
assert.equal(checkSummary([],[]).state,'HOLD_NO_CHECK_EVIDENCE');
assert.equal(checkSummary([ok],[]).state,'CHECKS_REPORTED_SUCCESS');
assert.equal(checkSummary([bad],[]).state,'HOLD_CHECKS_FAILED');
assert.equal(checkSummary([pending],[]).state,'HOLD_CHECKS_PENDING');
assert.equal(checkSummary([ok],[],{checksAccessible:false}).state,'HOLD_CHECKS_UNAVAILABLE');
assert.equal(checkSummary([ok],[{context:'ci',state:'failure'}]).state,'HOLD_CHECKS_FAILED');
assert.equal(checkSummary([ok],[{context:'ci',state:'success'}]).state,'CHECKS_REPORTED_SUCCESS');
assert.equal(checkSummary([bad,{...bad,conclusion:'success',started_at:'2026-11-02T00:00:00Z'}],[]).state,'CHECKS_REPORTED_SUCCESS');
assert.equal(checkSummary([{...ok,conclusion:'cancelled'}],[]).state,'HOLD_CHECKS_FAILED');
const pr={state:'open',draft:true,head:{sha:'abc'},number:1,html_url:'https://github.com/DavidWise01/jane/pull/1'};
assert.equal(disposition(pr,checkSummary([ok],[])),'REVIEW_READY_NO_AUTO_MERGE');
assert.equal(disposition({...pr,state:'closed'},{}),'HOLD_CLOSED_PR_RETRY_SUPPRESSED');
assert.equal(disposition({...pr,draft:false},{}),'HOLD_NON_DRAFT_PR');
assert.equal(disposition(null,{}),'NO_FORMIC_PR');
assert.equal(classifyLedger([{decision:'HOLD_CHECKS_FAILED'},{decision:'REVIEW_READY_NO_AUTO_MERGE'}]).failed,1);
const r={full_name:'DavidWise01/jane',private:false,visibility:'public',archived:false,disabled:false,fork:false,default_branch:'main'};
const policy={schema:'FORMIC-REPO-POLICY-v1',enabled:true,allowed_repairs:['BUG_REPORT_TEMPLATE'],max_open_pull_requests:1};
(async()=>{
 const report=await run({repos:[r],policyFn:async()=>policy,inspectFn:async()=>({repo:r.full_name,decision:'HOLD_CHECKS_FAILED'})});
 assert.equal(report.summary.failed,1);assert.equal(report.governance.automaticMerges,false);
 const excluded=await run({repos:[{...r,private:true}],policyFn:async()=>policy});assert.equal(excluded.summary.observed,0);
 console.log('PASS B162: check states, latest reruns, closed PR suppression, per-repo opt-in, no writes or merges');
})().catch(e=>{console.error(e);process.exitCode=1});
