'use strict';
const assert=require('node:assert/strict');
const {TEMPLATE}=require('./jane-b161-formic-agent.cjs');
const {parseTemplate}=require('./jane-b177-semantic-template.cjs');
const {fixtures}=require('./jane-b178-constraint-coverage.cjs');
const {parseIndependent,run,audit}=require('./jane-b179-independent-parser.cjs');
const canonicalA=parseTemplate(TEMPLATE),canonicalB=parseIndependent(TEMPLATE);
assert.deepEqual(canonicalB,canonicalA);
const report=run();
assert.equal(report.status,'INDEPENDENT_PARSER_AGREEMENT_NO_EXECUTION');
assert.equal(report.observed,48);
assert.equal(report.issues.length,0);
assert.equal(report.rows.every(x=>x.agreement===true),true);
assert.equal(audit(report).status,'PASS');
assert.equal(report.authority.mayCreatePR,false);
const permissive=run({secondary:()=>parseIndependent(TEMPLATE)});
assert.equal(permissive.status,'HOLD');
assert(permissive.issues.some(x=>x.startsWith('PARSER_DISAGREEMENT:')));
const overreject=run({secondary:()=>{throw Error('REJECT_EVERYTHING')}});
assert.equal(overreject.status,'HOLD');
assert(overreject.issues.includes('CANONICAL_DIFFERENTIAL_DISAGREEMENT'));
const missing=run({cases:fixtures().slice(1)});
assert.equal(missing.status,'HOLD');
assert(missing.issues.some(x=>x.startsWith('MISSING_CASE:')));
const changedContract=run({cases:fixtures().map((x,i)=>i===0?{...x,error:'UNEXPECTED_ACCEPTANCE'}:x)});
assert.equal(changedContract.status,'HOLD');
assert(changedContract.issues.some(x=>x.startsWith('CONTRACT_MISMATCH:')));
const changedAttestation={...report,authority:{...report.authority,mayMerge:true}};
assert.equal(audit(changedAttestation).status,'HOLD');
assert.throws(()=>parseIndependent(TEMPLATE.replace('labels: bug','labels: &alias')),/YAML_SPECIAL_OR_DYNAMIC/);
assert.throws(()=>parseIndependent(TEMPLATE.replace('## Environment','## Extra')),/HEADINGS/);
assert.throws(()=>parseIndependent(TEMPLATE.replace(/\n/g,'\r\n')),/ENCODING/);
console.log('PASS B179: 48 independent exact errors, canonical equivalence, missing / permissive / overreject HOLD');
