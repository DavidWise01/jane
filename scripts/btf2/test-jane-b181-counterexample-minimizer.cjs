'use strict';
const assert=require('node:assert/strict');
const {TEMPLATE}=require('./jane-b161-formic-agent.cjs');
const {minimize,run,audit,mismatch,observe,MAX_STEPS}=require('./jane-b181-counterexample-minimizer.cjs');
const clean=run();
assert.equal(clean.status,'NO_COUNTEREXAMPLES');
assert.equal(clean.generated,400);
assert.equal(clean.examples.length,0);
assert.equal(audit(clean).status,'PASS');
assert.equal(clean.authority.mayCreatePR,false);
assert.equal(clean.governance.noRepositoryCodeExecution,true);
const yes=()=>{throw Error('DIFFERENTIAL_FIRST')};
const no=()=>{throw Error('DIFFERENTIAL_SECOND')};
assert.equal(mismatch(observe(TEMPLATE,yes,no)),true);
const failing=minimize(TEMPLATE,{first:yes,second:no,maxSteps:MAX_STEPS});
assert.equal(failing.status,'COUNTEREXAMPLE_MINIMIZED');
assert.equal(failing.originalInput,TEMPLATE);
assert(failing.minimizedInput.length<TEMPLATE.length);
assert.deepEqual(failing.originalDecision,failing.minimizedDecision);
assert(failing.attempts<=MAX_STEPS);
assert.equal(failing.locallyMinimal,false);
const disagreement=run({first:yes,second:no,rounds:1});
assert.equal(disagreement.status,'COUNTEREXAMPLES_PRESERVED');
assert.equal(disagreement.examples.length,12);
assert.equal(audit(disagreement).status,'PASS');
for(const example of disagreement.examples){
 assert.equal(example.status,'COUNTEREXAMPLE_MINIMIZED');
 assert(example.minimized.bytes<=example.original.bytes);
 assert.equal(example.signature,JSON.stringify([false,'DIFFERENTIAL_FIRST',false,'DIFFERENTIAL_SECOND']));
}
const tampered=structuredClone(disagreement);
tampered.examples[0].minimizedInput='modified';
assert.equal(audit(tampered).status,'HOLD');
const altered={...clean,authority:{...clean.authority,mayMerge:true}};
assert.equal(audit(altered).status,'HOLD');
const noOriginal=minimize(TEMPLATE,{first:yes,second:yes});
assert.equal(noOriginal.status,'HOLD');
assert.equal(minimize(TEMPLATE,{first:yes,second:no,maxSteps:MAX_STEPS+1}).status,'HOLD');
console.log('PASS B181: no evidence invented; bounded shrink preserves precise mismatch, tamper and authority HOLD');
