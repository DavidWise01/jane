#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const {WitnessLedger}=require('./jane-b136-witnesses.cjs');
const l=new WitnessLedger();
const base={event:'Kr84-b134-context-A',source:'synthetic-source',metric:'retention_score',unit:'dimensionless',independence:'INDEPENDENT'};
const add=(id,witness,lower,value,upper,extra={})=>l.append({...base,id,witness,lower,value,upper,source:'independent-synthetic-'+witness,...extra});
add('A1','a1',0.81,0.85,0.89);
assert.deepEqual(l.compare(base.event).missing,['b1','c1']);
assert.equal(l.compare(base.event).status,'HOLD');
add('B1','b1',0.80,0.84,0.88);
add('C1','c1',0.82,0.86,0.90);
assert.equal(l.compare(base.event).compatible,true);
assert.equal(l.compare(base.event).status,'HOLD');
assert.equal(l.compare(base.event,{externalEvidenceApproved:true}).status,'ELIGIBLE_FOR_NEXT_GATE');
add('B2','b1',0.30,0.35,0.40);
assert.equal(l.compare(base.event,{externalEvidenceApproved:true}).status,'HOLD');
assert.ok(l.compare(base.event,{externalEvidenceApproved:true}).reasons.includes('NON_OVERLAPPING_INTERVALS'));
add('B3','b1',0.80,0.84,0.88,{independence:'SHARED_OR_UNKNOWN'});
assert.ok(l.compare(base.event,{externalEvidenceApproved:true}).reasons.includes('INDEPENDENCE_NOT_ESTABLISHED'));
add('B4','b1',0.8,0.84,0.88);
assert.equal(l.compare(base.event,{externalEvidenceApproved:true}).status,'ELIGIBLE_FOR_NEXT_GATE');
add('C2','c1',0.82,0.86,0.90,{unit:'percent'});
assert.ok(l.compare(base.event,{externalEvidenceApproved:true}).reasons.includes('INCOMPARABLE_METRICS_OR_UNITS'));
assert.throws(()=>add('C2','c1',0.82,0.86,0.9),/Duplicate/);
assert.throws(()=>add('X','a1',0.9,0.8,0.95),/Invalid observation/);
assert.deepEqual(l.audit(),{entries:7,chainVerified:true,quorumUsed:false,votesUsed:false});
assert.equal(l.entries[1].observation.value,0.84);
console.log('PASS B136: 7 immutable witness entries; missing, compatible, conflict, independence and unit mismatch; no quorum');
