import unittest,copy,tempfile,os
from transport import fixture,pack,identity,enc,demo
class TransportTests(unittest.TestCase):
 def setUp(self):
  self.dir=tempfile.TemporaryDirectory();self.path=os.path.join(self.dir.name,'audit.sqlite')
  self.audit,self.packet,self.key=fixture(self.path)
 def tearDown(self):self.dir.cleanup()
 def re_sign(self):self.packet['relay_signature']=self.key.sign(enc(self.packet['body'])).hex()
 def check(self,expected):self.assertEqual(self.audit.receive(self.packet,1500),expected)
 def test_valid(self):self.check('AUTHENTICATED_DELIVERY_FIXTURE')
 def test_replay(self):self.check('AUTHENTICATED_DELIVERY_FIXTURE');self.check('REPLAY')
 def test_restart_replay(self):self.check('AUTHENTICATED_DELIVERY_FIXTURE');a,_,_=fixture(self.path);self.assertEqual(a.receive(self.packet,1500),'REPLAY')
 def test_tamper_body(self):self.packet['body']['nonce']='tampered';self.check('BAD_RELAY_SIGNATURE')
 def test_bad_relay_sig(self):self.packet['relay_signature']='00'*64;self.check('BAD_RELAY_SIGNATURE')
 def test_missing_sig(self):self.packet.pop('relay_signature');self.check('MALFORMED')
 def test_unknown_relay(self):self.packet['body']['relay']='X';self.check('UNKNOWN_RELAY')
 def test_empty_nonce(self):self.packet['body']['nonce']='';self.check('BAD_NONCE')
 def test_nonce_too_long(self):self.packet['body']['nonce']='x'*129;self.check('BAD_NONCE')
 def test_bad_schema(self):self.packet['body']['schema']='v0';self.check('BAD_SCHEMA')
 def test_expired(self):self.assertEqual(self.audit.receive(self.packet,2001),'EXPIRED_ENVELOPE')
 def test_future(self):self.assertEqual(self.audit.receive(self.packet,-30001),'FUTURE_ENVELOPE')
 def test_bad_lifetime(self):self.packet['body']['expires_ms']=1000;self.check('BAD_LIFETIME')
 def test_excess_lifetime(self):self.packet['body']['expires_ms']=500000;self.check('BAD_LIFETIME')
 def test_large(self):self.audit.max_bytes=100;self.check('OVERSIZED')
 def test_missing_old(self):self.packet['body']['old_receipts']=[];self.re_sign();self.check('BAD_CHECKPOINT')
 def test_missing_new(self):self.packet['body']['new_receipts']=[];self.re_sign();self.check('BAD_CHECKPOINT')
 def test_duplicate_custodian(self):self.packet['body']['new_receipts'][2]=self.packet['body']['new_receipts'][0];self.re_sign();self.check('DUPLICATE_CUSTODIAN')
 def test_checkpoint_sig(self):self.packet['body']['new_receipts'][0]['signature']='00'*64;self.re_sign();self.check('BAD_CUSTODY_SIGNATURE')
 def test_checkpoint_tamper(self):self.packet['body']['new_receipts'][0]['body']=dict(self.packet['body']['new_receipts'][0]['body'],root='0'*64);self.re_sign();self.check('BAD_CUSTODY_SIGNATURE')
 def test_proof_corrupt(self):self.packet['body']['proof']['nodes'][0]='0'*64;self.re_sign();self.check('INVALID_CONSISTENCY_PROOF')
 def test_proof_missing(self):self.packet['body']['proof']={};self.re_sign();self.check('INVALID_CONSISTENCY_PROOF')
 def test_proof_size(self):self.packet['body']['proof']['old_size']=7;self.re_sign();self.check('INVALID_CONSISTENCY_PROOF')
 def test_old_new_swap(self):b=self.packet['body'];b['old_receipts'],b['new_receipts']=b['new_receipts'],b['old_receipts'];self.re_sign();self.check('CHECKPOINT_ROLLBACK')
 def test_invalid_time_type(self):self.assertEqual(self.audit.receive(self.packet,1.5),'BAD_LOCAL_TIME')
 def test_chain(self):self.check('AUTHENTICATED_DELIVERY_FIXTURE');self.assertEqual(self.audit.chain(),'VALID_LOCAL_CHAIN')
 def test_chain_tamper(self):
  self.check('AUTHENTICATED_DELIVERY_FIXTURE')
  with self.audit.conn() as c:c.execute("UPDATE events SET code='forged' WHERE seq=0")
  self.assertEqual(self.audit.chain(),'TAMPERED')
 def test_preserve_parent(self):self.check('AUTHENTICATED_DELIVERY_FIXTURE');self.assertEqual(self.audit.active_parent,'frozen_parent')
 def test_no_independence(self):self.assertFalse(demo()['independent_custodians_verified'])
 def test_deterministic(self):self.assertEqual(demo(),demo())
 def test_no_relay_self_certification(self):self.assertEqual(len(self.audit.keys),3)
 def test_nonce_distinct_accepts(self):
  self.check('AUTHENTICATED_DELIVERY_FIXTURE');self.packet['body']['nonce']='delivery-002';self.re_sign();self.check('AUTHENTICATED_DELIVERY_FIXTURE')
 def test_missing_packet(self):self.assertEqual(self.audit.receive(None,1500),'MALFORMED')
 def test_unknown_custodian(self):self.packet['body']['old_receipts'][0]['signer']='unknown';self.re_sign();self.check('UNKNOWN_CUSTODIAN')
 def test_short_old(self):self.packet['body']['old_receipts']=self.packet['body']['old_receipts'][:2];self.re_sign();self.check('INSUFFICIENT_DECLARED_ROOTS')
 def test_different_old_claims(self):self.packet['body']['old_receipts'][1]['body']=dict(self.packet['body']['old_receipts'][1]['body'],nonce='different');self.re_sign();self.check('CONFLICTING_CHECKPOINTS')
 def test_unchanged_signed_records(self):
  old=copy.deepcopy(self.packet['body']['old_receipts']);self.check('AUTHENTICATED_DELIVERY_FIXTURE');self.assertEqual(old,self.packet['body']['old_receipts'])
if __name__=='__main__':unittest.main(verbosity=2)