import sqlite3, tempfile, unittest
from pathlib import Path
from disclosure import FLAY203,Policy,Rejected,fixture
P=Policy(('a','b','c','d'),budget=12)
class Tests(unittest.TestCase):
 def setUp(self):
  self.tmp=tempfile.TemporaryDirectory();self.path=Path(self.tmp.name)/'audit.db';self.f=FLAY203(self.path,P)
 def tearDown(self):self.f.close();self.tmp.cleanup()
 def q(self,id='q1',subset=('a','b'),answer=.5,model='M'):return self.f.record('query',id=id,subset=subset,answer=answer,model=model)
 def reject(self,code,call):
  with self.assertRaisesRegex(Rejected,code):call()
 def test_empty(self):self.assertEqual(self.f.report()['used'],0)
 def test_first_cost(self):self.assertEqual(self.q()['body']['cost'],2)
 def test_overlap(self):self.q();self.assertEqual(self.q('q2',('b','c'))['body']['cost'],3)
 def test_repeat(self):self.q();self.assertEqual(self.q('q2')['body']['cost'],6)
 def test_budget_atomic(self):self.q();self.q('q2');self.reject('CUMULATIVE_BUDGET_EXCEEDED',lambda:self.q('q3'));self.assertEqual(len(self.f.events()),2)
 def test_duplicate(self):self.q();self.reject('DUPLICATE_QUERY',lambda:self.q())
 def test_empty_id(self):self.reject('INVALID_QUERY',lambda:self.q(''))
 def test_empty_model(self):self.reject('INVALID_QUERY',lambda:self.q(model=''))
 def test_empty_subset(self):self.reject('INVALID_SUBSET',lambda:self.q(subset=()))
 def test_duplicate_subset(self):self.reject('INVALID_SUBSET',lambda:self.q(subset=('a','a')))
 def test_unknown_subset(self):self.reject('INVALID_SUBSET',lambda:self.q(subset=('z',)))
 def test_outside_answer(self):self.reject('INVALID_ANSWER',lambda:self.q(answer=1.1))
 def test_bool_answer(self):self.reject('INVALID_ANSWER',lambda:self.q(answer=True))
 def test_nan_answer(self):self.reject('INVALID_ANSWER',lambda:self.q(answer=float('nan')))
 def test_adapt(self):self.q();self.f.record('adapt',model='N',based_on=['q1']);self.assertEqual(self.f.report()['adaptations'],1)
 def test_adapt_unknown(self):self.reject('UNKNOWN_FEEDBACK',lambda:self.f.record('adapt',model='N',based_on=['q1']))
 def test_adapt_empty(self):self.reject('INVALID_ADAPTATION',lambda:self.f.record('adapt',model='N',based_on=[]))
 def test_adapt_duplicate(self):self.q();self.reject('UNKNOWN_FEEDBACK',lambda:self.f.record('adapt',model='N',based_on=['q1','q1']))
 def test_seal(self):self.f.record('seal',model='M');self.assertTrue(self.f.report()['sealed'])
 def test_post_seal_query(self):self.f.record('seal',model='M');self.reject('SEALED_FINAL',self.q)
 def test_post_seal_adapt(self):self.f.record('seal',model='M');self.reject('SEALED_FINAL',lambda:self.f.record('adapt',model='M',based_on=['q']))
 def test_repeat_seal(self):self.f.record('seal',model='M');self.reject('SEALED_FINAL',lambda:self.f.record('seal',model='M'))
 def test_invalid_seal(self):self.reject('INVALID_SEAL',lambda:self.f.record('seal',model=''))
 def test_unknown_event(self):self.reject('UNKNOWN_EVENT',lambda:self.f.record('bogus'))
 def test_order_invariant_subset(self):self.q();self.assertEqual(self.q('q2',('b','a'))['body']['subset'],['a','b'])
 def test_coverage(self):self.q();self.assertEqual(self.f.report()['covered_cases'],2)
 def test_reopen(self):self.q();self.f.close();self.f=FLAY203(self.path,P);self.assertEqual(self.f.report()['total_queries'],1)
 def test_changed_policy(self):self.q();self.reject('POLICY_CHANGED',lambda:FLAY203(self.path,Policy(('a','b'))))
 def test_tampered_event(self):self.q();self.f.db.execute("UPDATE events SET body='{}' WHERE n=1");self.reject('CORRUPT_LOG',self.f.report)
 def test_tampered_hash(self):self.q();self.f.db.execute("UPDATE events SET hash='invalid' WHERE n=1");self.reject('CORRUPT_LOG',self.f.events)
 def test_tampered_previous(self):self.q();self.q('q2',('c',));self.f.db.execute("UPDATE events SET previous='invalid' WHERE n=2");self.reject('CORRUPT_LOG',self.f.report)
 def test_zero_budget(self):
  f=FLAY203(':memory:',Policy(('a',),budget=0));self.reject('CUMULATIVE_BUDGET_EXCEEDED',lambda:f.record('query',id='q',model='m',subset=['a'],answer=.5));f.close()
 def test_invalid_holdout(self):self.reject('invalid holdout',lambda:Policy(('a','a')))
 def test_invalid_cost(self):self.reject('invalid costs',lambda:Policy(('a',),base_cost=0))
 def test_fixture(self):self.assertEqual(fixture()['denied'],'CUMULATIVE_BUDGET_EXCEEDED')
if __name__=='__main__':unittest.main()